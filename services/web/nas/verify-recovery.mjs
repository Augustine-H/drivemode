// Offline verification only: does not contact providers or change NAS services.
import { readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { createDecipheriv, createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { DatabaseSync } from 'node:sqlite';
const [archive,keyFile,output]=process.argv.slice(2);
if(!archive||!keyFile||!output) throw Error('Expected encrypted backup, key file, isolated output directory');
const out=resolve(output); if(existsSync(out)) throw Error('Verification directory must be new');
const e=JSON.parse(readFileSync(archive,'utf8'));
if(e.format!=='VoiceGrokRecovery-v1'||e.algorithm!=='AES-256-GCM')throw Error('Unsupported backup');
const key=readFileSync(keyFile,'utf8').trim();if(!/^[a-f0-9]{64}$/.test(key))throw Error('Invalid key file');
const d=createDecipheriv('aes-256-gcm',Buffer.from(key,'hex'),Buffer.from(e.iv,'base64'));
d.setAAD(Buffer.from(e.format));d.setAuthTag(Buffer.from(e.tag,'base64'));
const tar=Buffer.concat([d.update(Buffer.from(e.ciphertext,'base64')),d.final()]);
mkdirSync(out,{mode:0o700});const temp=join(out,'snapshot.tar.gz');writeFileSync(temp,tar,{mode:0o600});
const entries=execFileSync('tar',['-tzf',temp],{encoding:'utf8'}).trim().split(/\r?\n/);
const allowed=/^(?:web|tts|network)\/(?:[A-Za-z0-9._-]+)?$|^manifest\.json$/;
if(entries.some(x=>!allowed.test(x)||x.includes('..')))throw Error('Unsafe archive entry');
const verbose=execFileSync('tar',['-tvzf',temp],{encoding:'utf8'}).trim().split(/\r?\n/);
if(verbose.some(x=>!['-','d'].includes(x[0])))throw Error('Links and special files are not supported');
execFileSync('tar',['-xzf',temp,'-C',out]);rmSync(temp);
const config=JSON.parse(readFileSync(join(out,'web/runtime.json'),'utf8'));
const adc=JSON.parse(readFileSync(join(out,'tts/adc.json'),'utf8'));
const token=readFileSync(join(out,'tts/backend-token'),'utf8').trim();
if(!config.login||!config.origin||!config.xaiApiKey||!adc.type||token.length<48||config.backends?.find(n=>n.id==='nas')?.token!==token)throw Error('Credential/configuration consistency failed');
const db=new DatabaseSync(join(out,'tts/usage.sqlite'),{readOnly:true});
if(db.prepare('PRAGMA integrity_check').get().integrity_check!=='ok')throw Error('Database integrity failed');
const counts={requests:db.prepare('SELECT COUNT(*) AS n FROM requests').get().n,segments:db.prepare('SELECT COUNT(*) AS n FROM segments').get().n,settings:db.prepare('SELECT COUNT(*) AS n FROM settings').get().n};
db.close();const manifest=JSON.parse(readFileSync(join(out,'manifest.json'),'utf8'));
console.log(JSON.stringify({authenticatedDecryption:true,credentialsConsistent:true,databaseIntegrity:'ok',counts,createdUtc:manifest.createdUtc,tailscaleStateIncluded:existsSync(join(out,'network/tailscaled.state')),sha256:createHash('sha256').update(readFileSync(archive)).digest('hex')}));
